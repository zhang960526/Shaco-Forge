export async function isolatedProfileLinks(dsh, runtime) {
  const links = new Map()
  async function visit(directory, prefix = '') {
    for (const name of await readdir(directory)) {
      const path = prefix + name, full = join(directory, name), info = await lstat(full)
      if (info.isSymbolicLink()) {
        const target = await realpath(full)
        assert.ok(path === 'profiles/shaco-forge' || /^profiles\/node_modules\/(?:@[^/]+\/)?[^/]+$/.test(path), 'ISOLATED_PROFILE_REFERENCE_SCOPE')
        assert.ok(target.startsWith(join(runtime, 'harness') + '\\'), 'ISOLATED_PROFILE_REFERENCE_TARGET')
        links.set(path, target)
      } else if (info.isDirectory()) await visit(full, path + '/')
    }
  }
  await visit(dsh); return links
}
export async function isolatedNative(operation, path, input) {
  assert.ok(resolve(path).startsWith(testRoot + '\\'))
  return new Promise((done, reject) => {
    const child = spawn(nativeTest, ['--fixture', operation, path], { cwd: resolve('.'), windowsHide: true, stdio: ['pipe', 'pipe', 'pipe'] })
    let output = '', diagnostic = ''
    child.stdout.on('data', data => { output += data })
    child.stderr.on('data', data => { diagnostic += data })
    const timer = setTimeout(() => { child.kill(); reject(new Error('ISOLATED_NATIVE_TIMEOUT')) }, 60_000)
    child.once('error', reject)
    child.once('exit', code => { clearTimeout(timer); if (code !== 0) reject(new Error('ISOLATED_NATIVE_REJECTED:' + (diagnostic.match(/[A-Z_]{8,}/g) ?? []).join(','))); else { try { done(JSON.parse(output)) } catch (error) { reject(error) } } })
    child.stdin.on('error', () => {}); child.stdin.end(input ?? '', 'utf8')
  })
}

export async function workerBridge(root, runtime, dsh) {
  const path = join(root, 'adapters', `worker-${randomUUID()}.mjs`)
  await mkdir(join(root, 'adapters'), { recursive: true })
  const config = { packagedRoot: runtime, harnessRoot: join(runtime, 'harness'), nativeHelperPath: join(runtime, RELEASE_LAYOUT.nativeHelper), dshHome: dsh, profileName: 'shaco-forge' }
  const from = relative => JSON.stringify(pathToFileURL(join(runtime, relative)).href)
  await writeFile(path, `// NOT_SHIPPED explicit isolated adapter, generated by the test runner.
import { mkdir, symlink, realpath, lstat } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { verifyPackagedRuntime } from ${from('resources/app/node_modules/@shaco-forge/contracts/dist/packaged-runtime.js')}
import { assertPackagedControl } from ${from('resources/app/worker/dist/control-preflight.js')}
import { startWorker } from ${from(RELEASE_LAYOUT.workerMain)}
const config = ${JSON.stringify(config)}
const release = await verifyPackagedRuntime(config.packagedRoot)
assertPackagedControl(config.packagedRoot, release, join(dirname(config.dshHome), 'control'), config.dshHome, process.argv.includes('--validate-upgrade'))
if (!process.argv.includes('--preflight')) {
  await mkdir(join(config.dshHome, 'profiles'), { recursive: true })
  const link = join(config.dshHome, 'profiles/shaco-forge'), expected = join(config.harnessRoot, 'profiles/shaco-forge')
  try { await symlink(expected, link, 'junction') } catch (error) { if (error.code !== 'EEXIST') throw error }
  if (!(await lstat(link)).isSymbolicLink() || await realpath(link) !== expected) throw new Error('TEST_PROFILE_REFERENCE_REJECTED')
}
await startWorker(config)
`, 'utf8')
  return path
}

export async function fixture(label, { step1 = false } = {}) {
  assert.match(label, /^[a-z0-9-]+$/)
  // An installed runtime under the checkout could discover development-only
  // ancestor modules. Match the packaged gate's external-root isolation.
  for (let directory = testRoot; ; directory = dirname(directory)) {
    assert.equal(existsSync(join(directory, 'node_modules')), false, 'ISOLATED_INSTALL_ANCESTRY_MUST_NOT_SUPPLY_DEVELOPMENT_MODULES')
    if (dirname(directory) === directory) break
  }
  const root = join(testRoot, `${label}-${Date.now()}-${randomUUID()}`)
  const payload = JSON.parse(await readFile('dist/packaged-runtime-location.json', 'utf8')).packagedRoot
  const paths = { payload, runtime: join(root, 'install/current'), dsh: join(root, 'data/dsh'), control: join(root, 'data/control'), backup: join(root, 'data/backup') }
  await isolatedNative('protect', root)
  await isolatedNative('protect', paths.control)
  const receipts = []
  const boundary = {
    protect: path => isolatedNative('protect', path),
    verifyAcl: async path => { const receipt = await isolatedNative('verify', path); receipts.push({ operation: 'ACL', path, ...receipt }) },
    publishJournal: async record => { await isolatedNative('journal', paths.control, jsonBytes(record)); receipts.push({ operation: 'JOURNAL', state: record.state, id: record.id }) },
    fence: (operation, dacl) => isolatedNative(operation === 'verify' ? 'fence-verify' : operation, paths.runtime, dacl),
    assertRegistrationClear: async () => {},
    rollbackRegistration: async () => { const { unlink } = await import('node:fs/promises'); await unlink(join(paths.control, 'test-registration.json')).catch(error => { if (error.code !== 'ENOENT') throw error }) },
    register: async target => { await writeFile(join(paths.control, 'test-registration.json'), jsonBytes(target), { encoding: 'utf8', flush: true }) },
    validationEntry: runtime => workerBridge(root, runtime, paths.dsh),
  }
  if (step1) {
    const prior = JSON.parse(await readFile('docs/04-development-records/evidence/V1-SLICE-3/STEP-2/S3STEP2-20260911-SAFETY-01/step1-source-location.json', 'utf8'))
    await verifyPackagedRuntime(prior.packagedRoot)
    await boundary.protect(paths.runtime); await boundary.protect(paths.dsh)
    await cp(prior.packagedRoot, paths.runtime, { recursive: true, force: false, errorOnExist: true })
    await writeFile(join(paths.dsh, 'isolated-durable-sentinel.bin'), Buffer.from('Shaco isolated fixture — 中文逐字节恢复', 'utf8'))
  }
  const publicFixture = await inspectAuthenticode(process.execPath, join(payload, RELEASE_LAYOUT.nativeHelper))
  assert.equal(publicFixture.status, 'Valid')
  // The direct adapter is fed an already signed PUBLIC verifier fixture; the
  // production entry always takes policy from its own sealed release manifest.
  const signature = { installer: process.execPath, digest: publicFixture.fileSha256,
    policy: { certificateSha256: [publicFixture.signer.sha256], timestampRequired: true }, nativeHelper: join(payload, RELEASE_LAYOUT.nativeHelper) }
  const operations = new InstallerOperations(paths, boundary, signature)
  return { root, paths, boundary, receipts, operations, signature }
}
